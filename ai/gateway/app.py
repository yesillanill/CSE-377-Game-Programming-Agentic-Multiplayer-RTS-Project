"""AI Gateway: the only HTTP endpoint Unity talks to.

    POST /v1/ask            {question, snapshot}   header X-RTS-Session: <per-match token generated by Unity>
    POST /v1/plan-decision  {request_id, decision, results}   (approval / rejection audit log from Unity)
    POST /bot/decide        VsAI bot decision layer (Laya)      header X-RTS-Session
    POST /plan/resolve      one ambiguous plan choice (Laya)    header X-RTS-Session
    POST /shutdown          stop the gateway (127.0.0.1 + one-time token given by the launching game only)
    GET  /health            {"status","laya","llm","device",...}

The gateway binds 127.0.0.1 only. It validates every body (pydantic, extra fields rejected, size limit), binds the
snapshot to the session token (a token cannot be reused for another match), runs the agent and returns a schema-valid
ActionPlan. Laya is loaded ONCE at startup in a background thread and kept in memory; every Laya-backed response
carries "laya_ms". If Laya cannot be loaded, the Laya layers are skipped and everything else keeps working.
"""

