"""AI Gateway: the only HTTP endpoint Unity talks to.

    POST /v1/ask            {question, snapshot}   header X-RTS-Session: <per-match token generated by Unity>
    POST /v1/plan-decision  {request_id, decision, results}   (approval / rejection audit log from Unity)
    GET  /health

The gateway binds 127.0.0.1 only. It validates the snapshot (pydantic, extra fields rejected), binds it to the
session token (a token cannot be reused for another match), runs the agent and returns a schema-valid ActionPlan.
"""

from __future__ import annotations

import asyncio
import os
import re
from contextlib import asynccontextmanager
from datetime import datetime, timezone

from fastapi import FastAPI, Header, HTTPException
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from agent.agent_runner import StrategicCommander
from agent.llm import OllamaClient
from agent.logging_utils import AgentLogger, session_hash
from mcp_server.session import SafeSnapshot, SessionStore
from rag.retriever import KnowledgeIndex

TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{16,64}$")
REQUEST_TIMEOUT = float(os.environ.get("RTS_REQUEST_TIMEOUT", "150"))


class AskRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    question: str = Field(min_length=1, max_length=600)
    snapshot: dict


class PlanDecision(BaseModel):
    model_config = ConfigDict(extra="forbid")
    request_id: str = Field(max_length=32)
    decision: str = Field(pattern="^(APPROVED|REJECTED)$")
    results: list[str] = Field(default_factory=list, max_length=16)


state: dict = {}


@asynccontextmanager
async def lifespan(_: FastAPI):
    state["llm"] = OllamaClient()
    state["logger"] = AgentLogger()
    state["commander"] = StrategicCommander(state["llm"], KnowledgeIndex.load(), state["logger"])
    state["sessions"] = SessionStore()
    state["locks"] = {}
    yield
    await state["llm"].aclose()


app = FastAPI(title="RTS AI Gateway", version="1.0", lifespan=lifespan)


def _check_token(token: str | None) -> str:
    if not token or not TOKEN_RE.match(token):
        raise HTTPException(status_code=401, detail="Missing or malformed X-RTS-Session token.")
    return token


@app.get("/health")
async def health() -> dict:
    llm = await state["llm"].health()
    return {"ok": True, "llm": llm, "time": datetime.now(timezone.utc).isoformat(timespec="seconds")}


@app.post("/v1/ask")
async def ask(body: AskRequest, x_rts_session: str | None = Header(default=None)) -> dict:
    token = _check_token(x_rts_session)
    try:
        snapshot = SafeSnapshot.model_validate(body.snapshot)
    except ValidationError as exc:
        state["logger"].log_security({"timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                                      "match_session": session_hash(token), "flags": ["invalid_snapshot"],
                                      # only the location and error type; never echo submitted values
                                      "detail": [{"loc": list(e["loc"]), "type": e["type"]} for e in exc.errors()[:5]]})
        raise HTTPException(status_code=422, detail="Snapshot failed validation.") from exc
    try:
        ctx = state["sessions"].bind(token, snapshot)
    except PermissionError as exc:
        state["logger"].log_security({"timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                                      "match_session": session_hash(token), "flags": ["session_match_mismatch"]})
        raise HTTPException(status_code=403, detail=str(exc)) from exc

    lock = state["locks"].setdefault(token, asyncio.Lock())
    if lock.locked():
        raise HTTPException(status_code=429, detail="Previous question is still being answered.")
    async with lock:
        try:
            return await asyncio.wait_for(state["commander"].run(ctx, body.question), timeout=REQUEST_TIMEOUT)
        except asyncio.TimeoutError as exc:
            raise HTTPException(status_code=504, detail="The AI took too long to answer.") from exc


@app.post("/v1/plan-decision")
async def plan_decision(body: PlanDecision, x_rts_session: str | None = Header(default=None)) -> dict:
    token = _check_token(x_rts_session)
    state["logger"].log_plan_decision({
        "timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "match_session": session_hash(token), "request_id": body.request_id,
        "decision": body.decision, "results": [r[:200] for r in body.results],
    })
    return {"ok": True}
