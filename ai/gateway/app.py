log = logging.getLogger("gateway")

TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{16,64}$")
REQUEST_TIMEOUT = float(os.environ.get("RTS_REQUEST_TIMEOUT", "150"))
BOT_DECIDE_TIMEOUT = float(os.environ.get("RTS_BOT_DECIDE_TIMEOUT", "1.2"))   # Unity waits 1.5 s at most
PLAN_RESOLVE_TIMEOUT = float(os.environ.get("RTS_PLAN_RESOLVE_TIMEOUT", "0.8"))
MAX_BODY_BYTES = int(os.environ.get("RTS_MAX_BODY_BYTES", str(64 * 1024)))
LOOPBACK_HOSTS = {"127.0.0.1", "::1", "localhost"}

# Set by gateway/__main__.py when the game started this process (one-time token read from a temp file).
_shutdown: dict = {"token": None, "stop": None}


def configure_shutdown(token: str | None, stop: Callable[[], None] | None) -> None:
    """Enables POST /shutdown for this process. Without a token (manual start) shutdown over HTTP is disabled."""
    _shutdown["token"] = token or None
    _shutdown["stop"] = stop


class AskRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    question: str = Field(min_length=1, max_length=600)
    snapshot: dict


class PlanDecision(BaseModel):
    """Unity AiPlanDecisionRecord: karar türü + seçilen / uygulanan / doğrulayıcı reddi sayıları (değerlendirme için)."""
    model_config = ConfigDict(extra="forbid")
    request_id: str = Field(max_length=32)
    decision: str = Field(pattern="^(FULL_APPROVE|PARTIAL_APPROVE|REJECT|ADVICE_ONLY)$")
    timestamp: str = Field(default="", max_length=40)
    match_id: str = Field(default="", max_length=64)
    ai_exec: bool = False
    plan_action_count: int = Field(default=0, ge=0, le=8)
    selected_count: int = Field(default=0, ge=0, le=8)
    applied_count: int = Field(default=0, ge=0, le=8)
    validator_rejected_count: int = Field(default=0, ge=0, le=8)
    rejection_reasons: list[str] = Field(default_factory=list, max_length=8)
    action_types: list[str] = Field(default_factory=list, max_length=8)


state: dict = {}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def init_state(llm=None, laya: LayaService | None = None, logger: AgentLogger | None = None,
               load_laya: bool = True) -> dict:
    """Builds the gateway state. Tests inject a fake LLM / fake Laya through this function."""
    state["llm"] = llm or OllamaClient()
    state["logger"] = logger or AgentLogger()
    state["laya"] = laya or LayaService()
    if load_laya and laya is None:
        state["laya"].start_background_load()  # preload once; /health shows "loading" until ready
    state["guard"] = InjectionGuard(state["laya"], state["logger"])
    state["commander"] = StrategicCommander(state["llm"], KnowledgeIndex.load(), state["logger"], guard=state["guard"])
    state["sessions"] = SessionStore()
    state["locks"] = {}
    state["bot_config"] = BotConfig.from_env()
    return state


@asynccontextmanager
async def lifespan(_: FastAPI):
    if not state:
        init_state()
    yield
    llm = state.get("llm")
    if llm is not None and hasattr(llm, "aclose"):
        await llm.aclose()


app = FastAPI(title="RTS AI Gateway", version="1.1", lifespan=lifespan)


@app.middleware("http")
async def limit_body_size(request: Request, call_next):
    """Rejects oversized bodies before they are parsed (Content-Length and actual size)."""
    if request.method == "POST":
        declared = request.headers.get("content-length")
        if declared is not None and declared.isdigit() and int(declared) > MAX_BODY_BYTES:
            return JSONResponse(status_code=413, content={"detail": "Request body too large."})
        body = await request.body()
        if len(body) > MAX_BODY_BYTES:
            return JSONResponse(status_code=413, content={"detail": "Request body too large."})
    return await call_next(request)


def _check_token(token: str | None) -> str:
    if not token or not TOKEN_RE.match(token):
        raise HTTPException(status_code=401, detail="Missing or malformed X-RTS-Session token.")
    return token


# ---------------------------------------------------------------------------------------------- health
@app.get("/health")
async def health() -> dict:
    llm = await state["llm"].health()
    laya: LayaService = state["laya"]
    llm_ready = bool(llm.get("reachable")) and bool(llm.get("model_installed"))
    if laya.status == "loading":
        overall = "loading"
    elif laya.ready and llm_ready:
        overall = "ready"
    elif laya.ready or llm_ready:
        overall = "degraded"
    else:
        overall = "failed"
    return {
        "ok": True, "status": overall,
        "laya": "ready" if laya.ready else ("failed" if laya.status in ("failed", "disabled") else "loading"),
        "llm": "ready" if llm_ready else "unreachable",
        "device": laya.device or "none",
        "laya_models": laya.models, "laya_error": laya.error, "laya_load_seconds": laya.load_seconds,
        "llm_detail": llm,  # {"reachable", "model", "model_installed"} (older launcher checks these keys)
        "shutdown_enabled": _shutdown["token"] is not None,
        "time": _now(),
    }


# ---------------------------------------------------------------------------------------------- AI Commander
@app.post("/v1/ask")
async def ask(body: AskRequest, x_rts_session: str | None = Header(default=None)) -> dict:
    token = _check_token(x_rts_session)
    try:
        snapshot = SafeSnapshot.model_validate(body.snapshot)
    except ValidationError as exc:
        state["logger"].log_security({"timestamp": _now(), "match_session": session_hash(token), "flags": ["invalid_snapshot"],
                                      # only the location and error type; never echo submitted values
                                      "detail": [{"loc": list(e["loc"]), "type": e["type"]} for e in exc.errors()[:5]]})
        raise HTTPException(status_code=422, detail="Snapshot failed validation.") from exc
    try:
        ctx = state["sessions"].bind(token, snapshot)
    except PermissionError as exc:
        state["logger"].log_security({"timestamp": _now(), "match_session": session_hash(token), "flags": ["session_match_mismatch"]})
        raise HTTPException(status_code=403, detail=str(exc)) from exc

    lock = state["locks"].setdefault(token, asyncio.Lock())
    if lock.locked():
        raise HTTPException(status_code=429, detail="Previous question is still being answered.")
    async with lock:
        # Extra Laya layer BEFORE the agent / LLM (code guards inside the agent still run afterwards)
        verdict = await state["guard"].check_question(body.question, token)
        if verdict.action == "blocked":
            lang = code_guard.detect_language(body.question, snapshot.ui_language)
            return blocked_response(lang, verdict, uuid.uuid4().hex[:12])
        try:
            result = await asyncio.wait_for(
                state["commander"].run(ctx, body.question, security_reminder=verdict.action == "flagged"),
                timeout=REQUEST_TIMEOUT)
        except asyncio.TimeoutError as exc:
            raise HTTPException(status_code=504, detail="The AI took too long to answer.") from exc
        result["laya"] = verdict.to_public()
        return result


@app.post("/v1/plan-decision")
async def plan_decision(body: PlanDecision, x_rts_session: str | None = Header(default=None)) -> dict:
    token = _check_token(x_rts_session)
    state["logger"].log_plan_decision({
        "timestamp": _now(), "match_session": session_hash(token), "request_id": body.request_id,
        "decision": body.decision, "ai_exec": body.ai_exec, "plan_action_count": body.plan_action_count,
        "selected_count": body.selected_count, "applied_count": body.applied_count,
        "validator_rejected_count": body.validator_rejected_count,
        "rejection_reasons": [r[:200] for r in body.rejection_reasons], "action_types": body.action_types,
    })
    return {"ok": True}


# ---------------------------------------------------------------------------------------------- VsAI bot (Laya)
@app.post("/bot/decide")
async def bot_decide(body: bot_decider.BotDecideRequest, x_rts_session: str | None = Header(default=None)) -> dict:
    token = _check_token(x_rts_session)
    laya: LayaService = state["laya"]
    if not laya.ready:
        # Unity then uses its own (identical) heuristic with w = 0: "AI opponent: simple mode"
        raise HTTPException(status_code=503, detail=f"laya_{laya.status}")
    t_start = time.perf_counter()
    cfg: BotConfig = state.get("bot_config") or BotConfig()
    zones = bot_decider.visible_zones(body)
    heur = bot_heuristic.heuristic(body, cfg, body.allowed_units, body.allowed_build, zones, body.allowed_maintenance)

    # 1) RAG enrichment from the SAME index search_game_knowledge uses (screened by the injection layer; never fatal)
    commander = state.get("commander")
    rag = await bot_rag.enrich(body, getattr(commander, "index", None), state.get("guard"), cfg, token, heur)

    # 2) Laya over feasible options only (hard constraints removed before asking), fixed English template
    text = bot_decider.build_state(body, rag.texts if rag.used else None, laya.bot_model)
    questions = bot_decider.build_questions(body, cfg)
    try:
        answers, ms = await laya.apredict(text, questions, laya.bot_model, BOT_DECIDE_TIMEOUT)
    except asyncio.TimeoutError as exc:
        raise HTTPException(status_code=504, detail="laya_timeout") from exc
    except LayaUnavailable as exc:
        raise HTTPException(status_code=503, detail="laya_unavailable") from exc
    decisions = bot_decider.to_decisions(answers, questions)

    # 3) utility blending: final = w * Laya + (1 - w) * heuristic
    blended = bot_decider.blended_decisions(body, decisions, cfg, cfg.blend_weight)
    total_ms = round((time.perf_counter() - t_start) * 1000.0, 1)
    state["logger"]._write("bot_gateway", {  # noqa: SLF001 - same JSONL writer, separate file
        "timestamp": _now(), "match_session": session_hash(token), "laya_ms": ms, "model": laya.bot_model,
        "questions": list(questions.keys()), "decisions": [{"id": d["id"], "choice": d["choice"], "p": d["p"]} for d in decisions],
        "blended": [{"id": d["id"], "choice": d["choice"], "p": d["p"]} for d in blended],
        "rag_used": rag.used, "rag_source_ids": rag.source_ids, "rag_latency_ms": rag.latency_ms,
        "rag_withheld": rag.withheld, "rag_error": rag.error, "total_ms": total_ms, "state_chars": len(text),
    })
    return {"ok": True, "laya_ms": ms, "model": laya.bot_model, "device": laya.device, "decisions": decisions,
            "blended": blended, "blend_weight": cfg.blend_weight, "target_zones": zones,
            "rag_used": rag.used, "rag_source_ids": rag.source_ids, "rag_latency_ms": rag.latency_ms,
            "total_ms": total_ms}


@app.post("/plan/resolve")
async def plan_resolve(body: plan_resolver.PlanResolveRequest, x_rts_session: str | None = Header(default=None)) -> dict:
    _check_token(x_rts_session)
    laya: LayaService = state["laya"]
    if not laya.ready:
        raise HTTPException(status_code=503, detail=f"laya_{laya.status}")
    text, question = plan_resolver.build_question(body)
    try:
        answers, ms = await laya.apredict(text, question, laya.bot_model, PLAN_RESOLVE_TIMEOUT)
    except asyncio.TimeoutError as exc:
        raise HTTPException(status_code=504, detail="laya_timeout") from exc
    except LayaUnavailable as exc:
        raise HTTPException(status_code=503, detail="laya_unavailable") from exc
    return {"ok": True, "laya_ms": ms, **plan_resolver.to_result(answers, question)}


# ---------------------------------------------------------------------------------------------- shutdown
@app.post("/shutdown")
async def shutdown(request: Request, x_rts_shutdown_token: str | None = Header(default=None)) -> dict:
    """Only the game instance that started this gateway knows the token; only loopback callers are accepted."""
    client = request.client.host if request.client else ""
    expected = _shutdown["token"]
    if client not in LOOPBACK_HOSTS or not expected or not x_rts_shutdown_token or \
            not hmac.compare_digest(expected.encode(), x_rts_shutdown_token.encode()):
        state["logger"].log_security({"timestamp": _now(), "flags": ["shutdown_rejected"], "loopback": client in LOOPBACK_HOSTS})
        raise HTTPException(status_code=403, detail="Shutdown not allowed.")
    log.warning("Shutdown requested by the game that started the gateway.")
    stop = _shutdown["stop"]
    if stop is not None:
        asyncio.get_running_loop().call_later(0.2, stop)  # reply first, then stop
    return {"ok": True}

